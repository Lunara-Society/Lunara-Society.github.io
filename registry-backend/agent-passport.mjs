/* ═══════════════════════════════════════════════════════════════════
   AGENT PASSPORTS — a credential an AI agent carries
   ═══════════════════════════════════════════════════════════════════

   A website passport is read from the outside. An agent has no outside,
   so it carries its passport: a small signed token, issued only for an
   AI agent whose Shield application a named reviewer approved, that it
   can present to any site, API or payment system:

       Lunara-Passport: <token>

   The receiver verifies it in one call (agentPassportVerify), or offline
   against the published key (agentPassportKeys). The call also reads the
   register live, so a passport stops working the moment the credential
   is revoked or expires, whatever the token says.

   Token: base64url(JSON payload) "." base64url(Ed25519 signature over
   the first part). The signing key is generated by this function on
   first use and kept in a table only the service role can read; nobody
   ever handles the private key, and it is never in this repository.
   ═══════════════════════════════════════════════════════════════════ */

const ISS = 'https://lunarasociety.com';
const enc = new TextEncoder();
const b64u = (bytes) => btoa(String.fromCharCode(...new Uint8Array(bytes))).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const unb64u = (s) => Uint8Array.from(atob(s.replace(/-/g, '+').replace(/_/g, '/') + '==='.slice((s.length + 3) % 4)), (c) => c.charCodeAt(0));

async function activeKey(deps) {
  let k = await deps.db.getActiveKey();
  if (!k) {
    const pair = await crypto.subtle.generateKey({ name: 'Ed25519' }, true, ['sign', 'verify']);
    const jwk = await crypto.subtle.exportKey('jwk', pair.publicKey);
    const kid = 'agent-' + new Date(deps.now()).toISOString().slice(0, 10) + '-' + jwk.x.slice(0, 8);
    k = { kid, public_jwk: { ...jwk, kid, use: 'sig', alg: 'EdDSA' }, private_pkcs8: b64u(await crypto.subtle.exportKey('pkcs8', pair.privateKey)), active: true, created_at: new Date(deps.now()).toISOString() };
    await deps.db.saveKey(k);
    k = (await deps.db.getActiveKey()) || k; // two first calls at once: keep whichever landed
  }
  return k;
}

export async function issue(entry, deps) {
  const k = await activeKey(deps);
  const payload = {
    v: 1, typ: 'lunara-agent-passport', iss: ISS, kid: k.kid,
    sub: entry.public_id, agent: entry.agent_name || entry.business_name, operator: entry.agent_operator || entry.business_name,
    domain: entry.domain || null, iat: Math.floor(deps.now() / 1000), exp: Math.floor(Date.parse(entry.expires_at) / 1000)
  };
  const head = b64u(enc.encode(JSON.stringify(payload)));
  const key = await crypto.subtle.importKey('pkcs8', unb64u(k.private_pkcs8), { name: 'Ed25519' }, false, ['sign']);
  return { token: head + '.' + b64u(await crypto.subtle.sign({ name: 'Ed25519' }, key, enc.encode(head))), payload };
}

export async function verify(token, deps) {
  const bad = (reason) => ({ success: true, valid: false, signature: 'invalid', reason });
  if (typeof token !== 'string' || token.length > 4096 || !/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(token)) return bad('That is not a Lunara agent passport.');
  const [head, sig] = token.split('.');
  let payload;
  try { payload = JSON.parse(new TextDecoder().decode(unb64u(head))); } catch { return bad('That is not a Lunara agent passport.'); }
  if (payload.typ !== 'lunara-agent-passport' || payload.iss !== ISS) return bad('That is not a Lunara agent passport.');
  const keys = (await deps.db.listKeys()) || [];
  const k = keys.find((x) => x.kid === payload.kid);
  if (!k) return bad('Signed with a key Lunara never published.');
  const pub = await crypto.subtle.importKey('jwk', { kty: k.public_jwk.kty, crv: k.public_jwk.crv, x: k.public_jwk.x }, { name: 'Ed25519' }, false, ['verify']);
  let ok = false;
  try { ok = await crypto.subtle.verify({ name: 'Ed25519' }, pub, unb64u(sig), enc.encode(head)); } catch { ok = false; }
  if (!ok) return bad('The signature does not match: this passport was altered or forged.');

  // The signature proves Lunara issued it. Whether it still stands is
  // the register's answer now, not the token's.
  const entry = await deps.db.getApplication(payload.sub);
  const now = deps.now();
  let status = 'not_registered';
  if (entry && entry.status === 'revoked') status = 'revoked';
  else if (entry && entry.status === 'approved') status = Date.parse(entry.expires_at) < now ? 'expired' : 'verified';
  const expired = payload.exp * 1000 < now;
  const valid = status === 'verified' && !expired;
  return {
    success: true, valid, signature: 'valid', status: expired && status === 'verified' ? 'expired' : status,
    agent: payload.agent, operator: payload.operator, domain: payload.domain, public_id: payload.sub,
    issued_at: new Date(payload.iat * 1000).toISOString(), expires_at: new Date(payload.exp * 1000).toISOString(),
    record: `${ISS}/registry.html?id=${encodeURIComponent(payload.sub)}`,
    reason: valid ? 'Issued by Lunara Society to an AI agent a named reviewer approved, and still in good standing.'
      : status === 'revoked' ? 'Genuine, but the credential was revoked. Do not rely on it.'
      : 'Genuine, but the credential is no longer current. Do not rely on it.'
  };
}

export async function agentPassportRoute(name, body, deps, h) {
  const { json, isOwner } = h;
  switch (name) {
    case 'agentPassportKeys': {
      const keys = ((await deps.db.listKeys()) || []).map((k) => k.public_jwk);
      return json({ success: true, issuer: ISS, keys });
    }
    case 'agentPassportVerify':
      return json(await verify(String(body.passport || body.token || '').trim(), deps));
    case 'agentPassportIssue': {
      const who = await deps.whoIs(body.session_token);
      if (!who) return json({ success: false, error: 'Sign in first.' }, 401);
      const id = String(body.public_id || '').trim().toUpperCase();
      const e = /^SHIELD-\d{4}-\d{4}$/.test(id) ? await deps.db.getApplication(id) : null;
      const mine = e && (String(e.contact_email || '').toLowerCase() === String(who.email).toLowerCase() || isOwner(who.email, deps.env));
      if (!mine) return json({ success: false, error: 'No credential with that ID belongs to this account.' }, 404);
      if (e.kind !== 'ai_agent') return json({ success: false, error: 'Passports are issued to verified AI agents. This credential is for a business.' }, 409);
      if (e.status !== 'approved' || Date.parse(e.expires_at) < deps.now()) return json({ success: false, error: 'Only a verified, current AI agent credential gets a passport.' }, 409);
      const { token, payload } = await issue(e, deps);
      return json({ success: true, passport: token, payload, header: `Lunara-Passport: ${token}`, verify: 'POST https://luiqtimzcsoqnizybifs.supabase.co/functions/v1/lunara-registry/agentPassportVerify {"passport":"…"}' });
    }
  }
  return null;
}
